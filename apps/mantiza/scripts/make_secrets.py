"""Writes Sources/Mantiza/Secrets.swift from the keys file outside the repo.

Development only: the keys end up inside the app on your own phone. Before the app goes to anyone
else, they move to a small key server (plan, section 4.3).

Also sets the debug inbox (tools/debug-inbox): development builds send a report of every task to
this PC over Wi-Fi. In keys.env, DEBUG_INBOX=off turns that off and DEBUG_INBOX=http://host:port
sets the address; when it is empty, this PC's Wi-Fi/LAN address on port 8765 is used.

Run from apps/mantiza (Windows or WSL):  python3 scripts/make_secrets.py
"""
import re
import secrets
import subprocess
import sys
from datetime import datetime
from pathlib import Path

CANDIDATES = [Path.home() / ".mantiza" / "keys.env", Path("/mnt/c/Users/PC/.mantiza/keys.env")]
keys_file = next((p for p in CANDIDATES if p.exists()), None)
if keys_file is None:
    sys.exit("keys.env not found (looked in: " + ", ".join(map(str, CANDIDATES)) + ")")

values = {}
for line in keys_file.read_text(encoding="utf-8").splitlines():
    m = re.match(r"\s*([A-Z_]+)\s*=\s*(.*)\s*$", line)
    if m:
        values[m.group(1)] = m.group(2).strip().strip('"').strip("'")


def swift(name):
    v = values.get(name, "")
    if not re.fullmatch(r"[A-Za-z0-9_\-\.]*", v):
        sys.exit(f"{name} has unexpected characters; check keys.env")
    return '"' + v + '"'


def pc_address():
    """This PC's IPv4 address on the network that has the default route (Wi-Fi or LAN)."""
    ps = ("(Get-NetIPConfiguration | Where-Object { $_.IPv4DefaultGateway -ne $null -and "
          "$_.NetAdapter.Status -eq 'Up' } | Select-Object -First 1).IPv4Address.IPAddress")
    for exe in ("powershell.exe", "powershell"):
        try:
            ip = subprocess.run([exe, "-NoProfile", "-Command", ps], capture_output=True, text=True,
                                timeout=30).stdout.strip()
        except (OSError, subprocess.SubprocessError):
            continue
        if re.fullmatch(r"\d+\.\d+\.\d+\.\d+", ip):
            return ip
    return ""


inbox = values.get("DEBUG_INBOX", "")
if inbox.lower() == "off":
    inbox = ""
elif not inbox:
    ip = pc_address()
    inbox = f"http://{ip}:8765" if ip else ""
if not re.fullmatch(r"[A-Za-z0-9:/\.\-]*", inbox):
    sys.exit("DEBUG_INBOX has unexpected characters; check keys.env")

token_file = keys_file.parent / "debug-token"
if not token_file.exists():
    token_file.write_text(secrets.token_hex(16), encoding="utf-8")
token = token_file.read_text(encoding="utf-8").strip()

try:
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                            cwd=Path(__file__).resolve().parent).stdout.strip()
except OSError:
    commit = ""
build = f"{commit or 'unknown'} built {datetime.now():%Y-%m-%d %H:%M}"

out = Path(__file__).resolve().parent.parent / "Sources" / "Mantiza" / "Secrets.swift"
out.write_text(
    "// Generated by scripts/make_secrets.py from keys.env. Never commit (it is in .gitignore).\n"
    "enum Secrets {\n"
    f"    static let openAI = {swift('OPENAI_API_KEY')}\n"
    f"    static let openRouter = {swift('OPENROUTER_API_KEY')}\n"
    f"    static let gemini = {swift('GEMINI_API_KEY')}\n"
    f'    static let debugInbox = "{inbox}"\n'
    f'    static let debugToken = "{token}"\n'
    f'    static let build = "{build}"\n'
    "}\n", encoding="utf-8")
print("Wrote", out.name, "with:", ", ".join(f"{k} {'set' if values.get(k) else 'EMPTY'}"
                                            for k in ("OPENAI_API_KEY", "OPENROUTER_API_KEY", "GEMINI_API_KEY"))
      + f"; debug inbox {inbox or 'off'}")
