"""Writes Sources/Mantiza/Secrets.swift from the keys file outside the repo.

Development only: the keys end up inside the app on your own phone. Before the app goes to anyone
else, they move to a small key server (plan, section 4.3).

Run from apps/mantiza (Windows or WSL):  python3 scripts/make_secrets.py
"""
import re
import sys
from pathlib import Path

CANDIDATES = [Path.home() / ".mantiza" / "keys.env", Path("/mnt/c/Users/PC/.mantiza/keys.env")]
keys_file = next((p for p in CANDIDATES if p.exists()), None)
if keys_file is None:
    sys.exit("keys.env not found (looked in: " + ", ".join(map(str, CANDIDATES)) + ")")

values = {}
for line in keys_file.read_text(encoding="utf-8").splitlines():
    m = re.match(r"\s*([A-Z_]+)\s*=\s*(.*)\s*$", line)
    if m:
        values[m.group(1)] = m.group(2).strip().strip('"').strip("'")


def swift(name):
    v = values.get(name, "")
    if not re.fullmatch(r"[A-Za-z0-9_\-\.]*", v):
        sys.exit(f"{name} has unexpected characters; check keys.env")
    return '"' + v + '"'


out = Path(__file__).resolve().parent.parent / "Sources" / "Mantiza" / "Secrets.swift"
out.write_text(
    "// Generated by scripts/make_secrets.py from keys.env. Never commit (it is in .gitignore).\n"
    "enum Secrets {\n"
    f"    static let openAI = {swift('OPENAI_API_KEY')}\n"
    f"    static let openRouter = {swift('OPENROUTER_API_KEY')}\n"
    f"    static let gemini = {swift('GEMINI_API_KEY')}\n"
    "}\n", encoding="utf-8")
print("Wrote", out.name, "with:", ", ".join(f"{k} {'set' if values.get(k) else 'EMPTY'}"
                                            for k in ("OPENAI_API_KEY", "OPENROUTER_API_KEY", "GEMINI_API_KEY")))
